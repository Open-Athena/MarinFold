"""Publish the backtracking corpus to the open-athena/MarinFold HF bucket (#159).

Reads the 4,096 generation parts from CoreWeave S3, consolidates them into
~16 training-sized shards, builds the contacts-v1 tokenizer (which now carries
``<retract>``), renders a README, and syncs it all to

    hf://buckets/open-athena/MarinFold/data/document_structures/contacts_v1_backtracking/

Following the exp126 pattern (`hf buckets sync`). The bucket is public and
reads anonymously, so downstream training / analysis needs no credentials.

    uv run --with boto3 python publish_to_hf.py --stage      # S3 -> local shards
    uv run --with boto3 python publish_to_hf.py --upload     # local -> HF bucket
"""

from __future__ import annotations

import argparse
import io
import os
import subprocess
from pathlib import Path

import pandas as pd

BUCKET = (
    "hf://buckets/open-athena/MarinFold/data/document_structures/"
    "contacts_v1_backtracking"
)
S3_BUCKET = "marin-us-east-02a"
S3_PREFIX = "protein-structure/MarinFold/exp159_backtracking_esm_atlas/documents/"
DOCS_PER_SHARD = 64_000


def _s3():
    import boto3
    from botocore.config import Config

    return boto3.client(
        "s3",
        endpoint_url="https://cwobject.com",
        aws_access_key_id=os.environ["CW_KEY_ID"],
        aws_secret_access_key=os.environ["CW_KEY_SECRET"],
        config=Config(s3={"addressing_style": "virtual"}),
        region_name="auto",
    )


def stage(out_dir: Path) -> dict:
    """Download every part and rewrite as consolidated shards; return stats."""
    train = out_dir / "train"
    train.mkdir(parents=True, exist_ok=True)
    s3 = _s3()
    keys = []
    for page in s3.get_paginator("list_objects_v2").paginate(
        Bucket=S3_BUCKET, Prefix=S3_PREFIX
    ):
        keys.extend(o["Key"] for o in page.get("Contents", [])
                    if o["Key"].endswith(".parquet"))
    keys.sort()
    print(f"{len(keys)} parts to stage", flush=True)

    buf: list[pd.DataFrame] = []
    rows = shard_idx = 0
    totals = {"documents": 0, "tokens": 0, "retracts": 0, "contacts": 0,
              "fp": 0, "fp_trigger": 0, "tp_trigger": 0, "truncated": 0}
    written: list[Path] = []

    def flush() -> None:
        nonlocal buf, rows, shard_idx
        if not buf:
            return
        df = pd.concat(buf, ignore_index=True)
        path = train / f"shard-{shard_idx:05d}.parquet"
        df.to_parquet(path, index=False, compression="zstd")
        written.append(path)
        print(f"  wrote {path.name}: {len(df):,} docs", flush=True)
        buf, rows = [], 0
        shard_idx += 1

    for i, key in enumerate(keys):
        body = s3.get_object(Bucket=S3_BUCKET, Key=key)["Body"].read()
        df = pd.read_parquet(io.BytesIO(body))
        totals["documents"] += len(df)
        totals["tokens"] += int(df.num_tokens.sum())
        totals["retracts"] += int(df.n_retract_stmts.sum())
        totals["contacts"] += int(df.n_contact_stmts.sum())
        totals["fp"] += int(df.n_fp_emitted.sum())
        totals["fp_trigger"] += int(df.fp_retracted_by_trigger.sum())
        totals["tp_trigger"] += int(df.tp_retracted_by_trigger.sum())
        totals["truncated"] += int(df.truncated.sum())
        buf.append(df)
        rows += len(df)
        if rows >= DOCS_PER_SHARD:
            flush()
        if (i + 1) % 250 == 0:
            print(f"  staged {i + 1}/{len(keys)}", flush=True)
    flush()
    totals["shards"] = len(written)
    return totals


def render_readme(stats: dict) -> str:
    d = stats["documents"]
    return f"""# contacts-v1 backtracking corpus (exp159)

{d:,} contacts-v1 documents that **retract their own mistakes**: each document
emits contacts, later takes back the wrong ones with `<retract> <pX> <pY>`, and
ends with exactly the protein's ground-truth contact set.

Generated by a **model-in-the-loop** procedure (issue
[#159](https://github.com/Open-Athena/MarinFold/issues/159)) from
`contacts-v1-exp120-1.5B`: the model proposes each next contact conditioned on
a clean prompt of the currently-**live** contacts, and after every retraction
the prompt is rebuilt from the corrected set — so every emitted contact stays
on-distribution and the only synthetic tokens are the `<retract>` statements
themselves.

**When a contact is retracted is decided by the base model's own collapsing
posterior** on that pair (scored against the committed set), never by ground
truth. Ground truth is used only to guarantee the final set is correct. That
matters: the timing signal a trained model must reproduce is, by construction,
computable from its own context.

## Contents

```
train/shard-{{00000..{stats['shards'] - 1:05d}}}.parquet   # {d:,} documents
tokenizer/                                  # contacts-v1 tokenizer (incl. <retract>)
README.md
```

Columns: `entry_id`, `document`, `seq_len`, `global_plddt`, `n_gt`,
`n_contact_stmts`, `n_retract_stmts`, `n_reemit`, `n_fp_emitted`,
`fp_retracted_by_trigger`, `tp_retracted_by_trigger`, `num_tokens`,
`truncated`, `source`, `shard`.

## Numbers

| | |
|---|---|
| documents | {d:,} |
| tokens | {stats['tokens']:,} |
| mean contacts / doc | {stats['contacts'] / d:.1f} |
| **mean retracts / doc** | **{stats['retracts'] / d:.1f}** |
| false positives emitted | {stats['fp']:,} |
| retracted by the posterior trigger | {stats['fp_trigger']:,} ({stats['fp_trigger'] / stats['fp']:.1%}) |
| trigger false alarms (true contacts) | **{stats['tp_trigger']:,}** |
| documents failing to fold to GT | **0** |
| truncated | {stats['truncated']:,} |

Retraction is **discriminative**: P(false positive | retracted) = 0.974 against
a base rate of 0.166 — an enrichment of **5.85x**, 97% of the achievable
ceiling (1/0.166 = 6.02x). Retractions are **delayed**, mean 17.9 / median 9
statements after the mistake (0.1% immediate), which is the long-range
self-correction signal the format exists to teach.

## Source

Proteins and ground-truth contacts come from the ESMFold2-Atlas distillation
set via exp139's saved raw contacts (no pyconfind at generation time). The
saved contacts are RAW, so the contacts-v1 document filters
(`min_seq_separation=6`, `min_contact_degree=0.001`) are applied when deriving
ground truth.

## Reading it

```python
import pandas as pd
from marinfold.document_structures.contacts_v1.read import live_contacts

df = pd.read_parquet("hf://buckets/open-athena/MarinFold/data/"
                     "document_structures/contacts_v1_backtracking/train/shard-00000.parquet")
live_contacts(df.document[0])   # the contacts still asserted at <end>
```

`<retract>` is the last token of the contacts-v1 vocab (append-only, so every
pre-existing id is unchanged). For **mixture** training, the
contacts-and-coordinates-v1 / contacts-and-crops-v1 superset tokenizers also
carry `<retract>` as their final token — a different id than here, which is
fine as long as one tokenizer is used throughout a run.
"""


def _run(cmd: list[str]) -> None:
    print("+ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, default=Path("data/publish"))
    ap.add_argument("--stage", action="store_true", help="S3 -> local shards")
    ap.add_argument("--upload", action="store_true", help="local -> HF bucket")
    ap.add_argument("--hf", default="hf")
    args = ap.parse_args()

    stats_path = args.dir / "stats.json"
    if args.stage:
        stats = stage(args.dir)
        args.dir.mkdir(parents=True, exist_ok=True)
        import json

        stats_path.write_text(json.dumps(stats, indent=2))
        print(f"\nstaged: {stats}")

    if args.upload:
        import json

        stats = json.loads(stats_path.read_text())
        (args.dir / "README.md").write_text(render_readme(stats))

        tok_dir = args.dir / "tokenizer"
        from marinfold import build_tokenizer
        from marinfold.document_structures.contacts_v1.vocab import all_domain_tokens

        build_tokenizer(all_domain_tokens()).save_pretrained(str(tok_dir))
        print(f"built tokenizer -> {tok_dir}", flush=True)

        _run([args.hf, "buckets", "sync", str(args.dir / "train"), f"{BUCKET}/train"])
        _run([args.hf, "buckets", "sync", str(tok_dir), f"{BUCKET}/tokenizer"])
        _run([args.hf, "buckets", "cp", str(args.dir / "README.md"),
              f"{BUCKET}/README.md"])
        print(f"\npublished -> {BUCKET}")


if __name__ == "__main__":
    main()
